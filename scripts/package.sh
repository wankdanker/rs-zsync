#!/bin/sh
# Build a static release of zsync for TARGET: the bare executable, a tarball and a .deb.
#
#   scripts/package.sh x86_64-unknown-linux-musl    # or aarch64-unknown-linux-musl
#
# Run it on a host of the same architecture (the build runs the binary to generate shell
# completions). Needs: rustup target TARGET, cargo-deb. Outputs go to dist/.
set -eu

TARGET=${1:?usage: scripts/package.sh TARGET}
cd "$(dirname "$0")/.."

VERSION=$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -n1)
case "$TARGET" in
    x86_64-*) ARCH=x86_64 ;;
    aarch64-*) ARCH=aarch64 ;;
    *) ARCH=${TARGET%%-*} ;;
esac

cargo build --release --locked --target "$TARGET"
BIN="target/$TARGET/release/zsync"
"$BIN" version

# Shell completions, generated by clyops from the CLI definition.
mkdir -p target/completions
"$BIN" --completion bash > target/completions/zsync.bash
"$BIN" --completion zsh > target/completions/_zsync
"$BIN" --completion fish > target/completions/zsync.fish

mkdir -p dist
NAME="zsync-$VERSION-$ARCH-linux"
# The bare static executable, usable as-is on any Linux of this architecture.
cp "$BIN" "dist/$NAME"
STAGE="target/stage/$NAME"
rm -rf "$STAGE"
mkdir -p "$STAGE/completions"
cp "$BIN" README.md LICENSE CHANGELOG.md "$STAGE/"
cp docs/FEATURES.md "$STAGE/"
cp target/completions/* "$STAGE/completions/"
tar -C target/stage -czf "dist/$NAME.tar.gz" "$NAME"

cargo deb --no-build --no-strip --target "$TARGET" --output dist/
ls -l dist/
